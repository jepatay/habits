// Firebase Cloud Messaging requires firebase-messaging-sw.js to be a plain
// static file at the origin root, so it can't read import.meta.env like the
// rest of the app. This writes the (public, non-secret) Firebase web config
// into it from .env before dev/build so both stay in sync.
const fs = require('fs');
const path = require('path');

function loadEnv() {
  const envPath = path.join(__dirname, '..', '.env');
  const env = { ...process.env };
  if (fs.existsSync(envPath)) {
    for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
      const match = line.match(/^\s*([\w.]+)\s*=\s*(.*)?\s*$/);
      if (match) env[match[1]] = (match[2] || '').trim().replace(/^['"]|['"]$/g, '');
    }
  }
  return env;
}

const env = loadEnv();
const config = {
  apiKey: env.VITE_FIREBASE_API_KEY || '',
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN || '',
  projectId: env.VITE_FIREBASE_PROJECT_ID || '',
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET || '',
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
  appId: env.VITE_FIREBASE_APP_ID || '',
};

const content = `// Auto-generated by scripts/generate-messaging-sw.cjs - do not edit directly.
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const { title, body } = payload.notification || {};
  self.registration.showNotification(title || 'Habit reminder', {
    body: body || "Don't forget to check off today's habits.",
    icon: '/pwa-192.png',
    badge: '/pwa-192.png',
  });
});
`;

fs.writeFileSync(path.join(__dirname, '..', 'public', 'firebase-messaging-sw.js'), content);
console.log('Generated public/firebase-messaging-sw.js');
